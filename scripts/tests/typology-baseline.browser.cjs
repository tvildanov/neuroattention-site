'use strict';
const { chromium }=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
(async()=>{
 const launch={headless:true};
 if(process.env.DOM_TYPOLOGY_CHROMIUM)launch.executablePath=process.env.DOM_TYPOLOGY_CHROMIUM;
 const browser=await chromium.launch(launch);
 const context=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true});
 const page=await context.newPage();let errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/typology-baseline.html');
 await page.getByRole('button',{name:'Начать',exact:true}).click();
 await page.getByRole('button',{name:'Далее',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Выберите ответ'}).waitFor();
 await page.locator('fieldset input').first().check();
 await page.getByRole('button',{name:'Далее',exact:true}).click();
 await page.getByRole('button',{name:'Пропустить',exact:true}).click();
 const key=await page.evaluate(()=>Object.keys(localStorage).find(k=>k.startsWith('dom_typology_draft:')));
 const before=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key);
 assert.equal(before.cursor,2);
 const title=await page.locator('h1').innerText();
 await page.reload();await page.getByRole('button',{name:'Продолжить',exact:true}).click();
 assert.equal(await page.locator('h1').innerText(),title);
 let steps=0;
 while(await page.locator('fieldset').count()){
  const rank=await page.getByText('Выберите два действия по очереди: сначала первое, затем второе.',{exact:true}).count();
  await page.locator('fieldset input').nth(0).check();
  if(rank)await page.locator('fieldset input').nth(1).check();
  await page.getByRole('button',{name:'Далее',exact:true}).click();
  if(++steps>45)throw Error('Did not reach results');
 }
 await page.getByRole('heading',{name:'Сведения собраны',exact:true}).waitFor();
 assert.equal(await page.locator('details').count(),13);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 const dl=page.waitForEvent('download');
 await page.getByRole('button',{name:'Скачать ответы',exact:true}).click();
 const download=await dl;
 const exported=JSON.parse(await fs.readFile(await download.path(),'utf8'));
 assert.equal(Object.keys(exported.session.answers).length,41);
 assert.equal(exported.summary.stats[0].responses.skipped,1);
 assert.equal(exported.summary.stats.length,13);
 assert.equal(exported.summary.profile,null);
 assert.ok(exported.summary.stats.every(s=>s.score===null));
 await page.screenshot({path:'/tmp/dom-typology-mobile-results.png',fullPage:true});
 await page.setViewportSize({width:1366,height:900});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 await context.close();

 const bad=await browser.newContext();
 const bp=await bad.newPage();
 await bp.goto('http://127.0.0.1:8765/typology-baseline.html');
 await bp.getByRole('button',{name:'Начать',exact:true}).waitFor();
 await bp.evaluate(()=>localStorage.setItem('dom_typology_draft:dom-baseline-13:draft-2026-11-17.1','{invalid-json'));
 await bp.reload();await bp.getByRole('heading',{name:'Черновик не удалось открыть'}).waitFor();
 assert.equal(await bp.evaluate(()=>localStorage.getItem('dom_typology_draft:dom-baseline-13:draft-2026-11-17.1')),'{invalid-json');
 await bad.close();

 const blocked=await browser.newContext();
 await blocked.addInitScript(()=>{Storage.prototype.setItem=function(){throw new DOMException('blocked','QuotaExceededError');};});
 const pp=await blocked.newPage();
 await pp.goto('http://127.0.0.1:8765/typology-baseline.html');
 await pp.getByRole('button',{name:'Начать',exact:true}).click();
 await pp.locator('fieldset input').first().check();
 await pp.getByRole('button',{name:'Далее',exact:true}).click();
 await pp.getByRole('status').filter({hasText:'Скачайте ответы перед выходом'}).waitFor();
 await blocked.close();
 await browser.close();
 process.stdout.write('Browser checks passed: mobile/desktop, required answer, skip, reload/resume, 41 responses, 13 summaries, JSON export, no invented scores, corrupt storage preservation, storage failure warning.\n');
})().catch(e=>{console.error(e);process.exit(1);});
